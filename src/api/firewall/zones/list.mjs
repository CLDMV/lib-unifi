import { officialRead } from "../../../lib/crud.mjs";

/**
 * @fileoverview `firewall.zones.list()` — the site's firewall zones (the predefined
 * internal/external/hotspot/vpn zones plus custom ones) with the network ids
 * each carries. Official-only.
 *
 * @returns {Promise<object[]>} the collection as the official Integration API
 *   answers it (each page merged; the rows are the API's own shape)
 * @throws {CapabilityError} when the official surface is unavailable
 */
export default async function list() {
	return officialRead("firewall.zones", "firewall/zones", { topLevel: false, idOf: (item) => item?.id });
}
